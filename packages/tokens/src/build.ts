/**
 * Token generator: tokens.json → dist/tokens.css (variables), dist/theme.css (Tailwind v4 bridge),
 * dist/tokens.ts (typed values for JS), dist/contrast.json (audit).
 *
 * Fails (exit 1) if any declared contrast pair misses its minimum in either theme.
 * Run: node packages/tokens/src/build.ts [--check]   (--check: fail if dist/ would change)
 * dist/ is generated (gitignored); the build exits non-zero on any contrast failure, which is the CI gate.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { contrastRatio, formatOklch, maxChroma, parseOklch, toHex, type Oklch } from "./color.ts";

type ScaleSpec = { hue: number; chromaPct?: number; fixedChroma?: number; lightChroma?: number };
type ContrastRule = { fg: string; bg: string[]; min: number; note?: string };
type TypeSpec = { size: string; lineHeight: string; tracking?: string };
type Tokens = {
  color: {
    steps: Record<string, number>;
    scales: Record<string, ScaleSpec>;
    semantic: { light: Record<string, string>; dark: Record<string, string> };
    contrast: ContrastRule[];
  };
  radius: Record<string, string>;
  z: Record<string, number>;
  motion: { duration: Record<string, string>; ease: Record<string, string> };
  type: Record<string, TypeSpec>;
};
type Theme = "light" | "dark";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");
const HEADER = "/* GENERATED by packages/tokens/src/build.ts from tokens.json. Do not edit. */\n";

const tokens: Tokens = JSON.parse(readFileSync(join(ROOT, "tokens.json"), "utf8"));

// ---------------------------------------------------------------- primitives
function buildScale(spec: ScaleSpec): Record<string, Oklch> {
  const out: Record<string, Oklch> = {};
  for (const [step, l] of Object.entries(tokens.color.steps)) {
    let c: number;
    if (spec.fixedChroma !== undefined) {
      const lightEnd = step === "50" || step === "100";
      c = Math.min(
        lightEnd ? (spec.lightChroma ?? spec.fixedChroma) : spec.fixedChroma,
        maxChroma(l, spec.hue),
      );
    } else {
      c = (spec.chromaPct ?? 0.8) * maxChroma(l, spec.hue);
      // Keep the ends calm: tints and the deepest step carry less chroma.
      if (step === "50") c *= 0.35;
      else if (step === "100") c *= 0.55;
      else if (step === "950") c *= 0.7;
    }
    out[step] = { l, c: Number(c.toFixed(3)), h: spec.hue, alpha: 1 };
  }
  return out;
}

const primitives: Record<string, Record<string, Oklch>> = Object.fromEntries(
  Object.entries(tokens.color.scales).map(([name, spec]) => [name, buildScale(spec)]),
);

// ---------------------------------------------------------------- semantics
const REF_RE = /^([a-z]+)\.(\d+)$/;

function resolve(value: string): { color: Oklch; css: string } {
  const ref = REF_RE.exec(value);
  if (ref) {
    const [, scale, step] = ref;
    const color = primitives[scale!]?.[step!];
    if (!color) throw new Error(`Unknown primitive reference: ${value}`);
    return { color, css: `var(--${scale}-${step})` };
  }
  const color = parseOklch(value);
  return { color, css: formatOklch(color) };
}

const themes: Theme[] = ["light", "dark"];
const semanticNames = Object.keys(tokens.color.semantic.light);
for (const theme of themes) {
  const names = Object.keys(tokens.color.semantic[theme]);
  const missing = semanticNames.filter((n) => !names.includes(n));
  const extra = names.filter((n) => !semanticNames.includes(n));
  if (missing.length || extra.length) {
    throw new Error(`Theme ${theme} token mismatch. missing=${missing} extra=${extra}`);
  }
}
const resolved = Object.fromEntries(
  themes.map((t) => [
    t,
    Object.fromEntries(semanticNames.map((n) => [n, resolve(tokens.color.semantic[t][n]!)])),
  ]),
) as Record<Theme, Record<string, { color: Oklch; css: string }>>;

// ---------------------------------------------------------------- contrast audit
type Audit = { theme: Theme; fg: string; bg: string; ratio: number; min: number; pass: boolean };
const audit: Audit[] = [];
for (const theme of themes) {
  for (const rule of tokens.color.contrast) {
    for (const bg of rule.bg) {
      const fg = resolved[theme][rule.fg];
      const back = resolved[theme][bg];
      if (!fg || !back) throw new Error(`Contrast rule references unknown token: ${rule.fg} on ${bg}`);
      if (fg.color.alpha < 1 || back.color.alpha < 1)
        throw new Error(`Contrast rule uses translucent token: ${rule.fg} on ${bg}`);
      const ratio = contrastRatio(fg.color, back.color);
      audit.push({
        theme,
        fg: rule.fg,
        bg,
        ratio: Number(ratio.toFixed(2)),
        min: rule.min,
        pass: ratio >= rule.min,
      });
    }
  }
}

// ---------------------------------------------------------------- emit
const indent = (lines: string[]) => lines.map((l) => `  ${l}`).join("\n");

const primitiveLines = Object.entries(primitives).flatMap(([scale, steps]) =>
  Object.entries(steps).map(([step, c]) => `--${scale}-${step}: ${formatOklch(c)}; /* ${toHex(c)} */`),
);
const semanticLines = (theme: Theme) => semanticNames.map((n) => `--${n}: ${resolved[theme][n]!.css};`);
const staticLines = [
  ...Object.entries(tokens.radius).map(([k, v]) => `--radius-${k}: ${v};`),
  ...Object.entries(tokens.z).map(([k, v]) => `--z-${k}: ${v};`),
  ...Object.entries(tokens.motion.duration).map(([k, v]) => `--duration-${k}: ${v};`),
  ...Object.entries(tokens.motion.ease).map(([k, v]) => `--ease-${k}: ${v};`),
];

const tokensCss = `${HEADER}
/* Primitives: scales for reference only. Components use semantic tokens. */
:root {
${indent(primitiveLines)}
}

/* Semantic tokens: light (default) */
:root {
${indent([...semanticLines("light"), ...staticLines, "color-scheme: light;"])}
}

/* Semantic tokens: dark (class set by the theme script) */
:root.dark,
.dark {
${indent([...semanticLines("dark"), "color-scheme: dark;"])}
}

/* No-JS fallback: follow the OS until a theme class is set */
@media (prefers-color-scheme: dark) {
  :root:not(.light):not(.dark) {
${semanticLines("dark")
  .map((l) => `    ${l}`)
  .join("\n")}
    color-scheme: dark;
  }
}

/* Reduced motion: OS setting (unless the user chose "full" in settings) or the in-app toggle */
@media (prefers-reduced-motion: reduce) {
  :root:not([data-motion="full"]) {
    --duration-fast: 0ms;
    --duration-base-in: 0ms;
    --duration-base-out: 0ms;
    --duration-slow: 0ms;
    --duration-celebrate: 0ms;
  }
}
:root[data-motion="reduce"] {
  --duration-fast: 0ms;
  --duration-base-in: 0ms;
  --duration-base-out: 0ms;
  --duration-slow: 0ms;
  --duration-celebrate: 0ms;
}
`;

const toUtility = (n: string) => (n === "text" ? "fg" : n.startsWith("text-") ? `fg-${n.slice(5)}` : n);

const themeCss = `${HEADER}
/*
 * Tailwind v4 bridge. Import after "tailwindcss" and @devgrill/tokens/tokens.css.
 * Tailwind's default palette is removed so only semantic colours exist (e.g. bg-surface,
 * text-fg-muted, border-border). Raw palette classes like bg-red-500 do not compile.
 */
@custom-variant dark (&:where(.dark, .dark *));

@theme {
  --color-*: initial;
}

@theme inline {
${indent(semanticNames.map((n) => `--color-${toUtility(n)}: var(--${n});`))}

${indent(Object.keys(tokens.radius).map((k) => `--radius-${k}: var(--radius-${k});`))}

  --font-sans: var(--font-ui), ui-sans-serif, system-ui, "Segoe UI", sans-serif;
  --font-serif: var(--font-editorial), ui-serif, Georgia, serif;
  --font-mono: var(--font-code), ui-monospace, "Cascadia Code", Consolas, monospace;
  --font-display: var(--font-arcade, var(--font-ui)), ui-sans-serif, sans-serif;

${indent(
  Object.entries(tokens.type).flatMap(([name, t]) => [
    `--text-${name}: ${t.size};`,
    `--text-${name}--line-height: ${t.lineHeight};`,
    ...(t.tracking ? [`--text-${name}--letter-spacing: ${t.tracking};`] : []),
  ]),
)}

${indent(Object.keys(tokens.motion.ease).map((k) => `--ease-${k}: var(--ease-${k});`))}

  --shadow-float: 0 1px 2px var(--shadow), 0 12px 32px -8px var(--shadow);
  --shadow-overlay: 0 24px 64px -16px var(--shadow);
}
`;

const ms = (v: string) => Number.parseInt(v, 10);
const tokensTs = `// GENERATED by packages/tokens/src/build.ts from tokens.json. Do not edit.

export const semanticTokens = ${JSON.stringify(semanticNames)} as const;
export type SemanticToken = (typeof semanticTokens)[number];

/** Resolved colours per theme (oklch strings), e.g. for canvas-drawn charts. */
export const themeColors = ${JSON.stringify(
  Object.fromEntries(
    themes.map((t) => [
      t,
      Object.fromEntries(semanticNames.map((n) => [n, formatOklch(resolved[t][n]!.color)])),
    ]),
  ),
  null,
  2,
)} as const satisfies Record<"light" | "dark", Record<SemanticToken, string>>;

export const chartSeries = ["chart-1", "chart-2", "chart-3", "chart-4", "chart-5", "chart-6", "chart-7", "chart-8"] as const;

/** Durations in ms (0 when the user prefers reduced motion; resolve via CSS vars at runtime). */
export const durationsMs = ${JSON.stringify(Object.fromEntries(Object.entries(tokens.motion.duration).map(([k, v]) => [k, ms(v)])))} as const;

export const easings = ${JSON.stringify(tokens.motion.ease)} as const;

/** Cubic-bezier control points for JS animation libraries (motion). */
export const easingPoints = ${JSON.stringify(
  Object.fromEntries(
    Object.entries(tokens.motion.ease).map(([k, v]) => [
      k,
      v
        .replace(/cubic-bezier\(|\)/g, "")
        .split(",")
        .map(Number),
    ]),
  ),
)} as unknown as Record<keyof typeof easings, [number, number, number, number]>;

export const zIndex = ${JSON.stringify(tokens.z)} as const;
`;

const contrastJson =
  JSON.stringify(
    {
      generatedFrom: "tokens.json",
      pairs: audit.length,
      failures: audit.filter((a) => !a.pass).length,
      audit,
    },
    null,
    2,
  ) + "\n";

const outputs: Record<string, string> = {
  "tokens.css": tokensCss,
  "theme.css": themeCss,
  "tokens.ts": tokensTs,
  "contrast.json": contrastJson,
};

const check = process.argv.includes("--check");
let stale = false;
mkdirSync(DIST, { recursive: true });
for (const [file, content] of Object.entries(outputs)) {
  const path = join(DIST, file);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  if (check) {
    stale = true;
    console.error(`tokens: dist/${file} is stale (run pnpm --filter @devgrill/tokens build)`);
  } else {
    writeFileSync(path, content, "utf8");
    console.log(`tokens: wrote dist/${file}`);
  }
}

const failures = audit.filter((a) => !a.pass);
const passCount = audit.length - failures.length;
console.log(`tokens: contrast ${passCount}/${audit.length} pairs pass (light + dark)`);
for (const f of failures) {
  console.error(`  FAIL [${f.theme}] ${f.fg} on ${f.bg}: ${f.ratio}:1 < ${f.min}:1`);
}
if (failures.length || stale) process.exit(1);
